static void OV2640_Write_Array(const unsigned char bytes[][2])
{
    uint32_t i = 0;
    while (bytes[i][0] != 0x00 || bytes[i][1] != 0x00)
    {
        OV2640_WR_Reg(bytes[i][0], bytes[i][1]);
        i++;
    }
}

