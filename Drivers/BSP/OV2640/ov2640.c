uint8_t OV2640_Init(void)
{
    #ifdef CAM_RST_GPIO_Port
    HAL_GPIO_WritePin(CAM_RST_GPIO_Port, CAM_RST_Pin, GPIO_PIN_RESET);
    HAL_Delay(50);
    HAL_GPIO_WritePin(CAM_RST_GPIO_Port, CAM_RST_Pin, GPIO_PIN_SET);
    HAL_Delay(50);
    #endif

    OV2640_WR_Reg(OV2640_DSP_RA_DLMT, OV2640_BANK_SENSOR);
    OV2640_WR_Reg(OV2640_SENSOR_COM7, OV2640_COM7_RESET);
    HAL_Delay(100);

    OV2640_Write_Array(OV2640_INIT_REGS);
    return 0;
}

uint8_t OV2640_Set_JPEG_Quality(uint8_t quality)
{
    OV2640_WR_Reg(OV2640_DSP_RA_DLMT, OV2640_BANK_DSP);
    return OV2640_WR_Reg(OV2640_DSP_QS, quality);
}

uint8_t OV2640_Set_Resolution(ov2640_resolution_t res)
{
    switch (res)
    {
        case OV2640_RES_320x240:
            OV2640_Write_Array(OV2640_JPEG_QVGA);
            break;
        case OV2640_RES_640x480:
            OV2640_Write_Array(OV2640_JPEG_VGA);
            break;
        default:
            return 1;
    }
    return 0;
}

uint8_t OV2640_Init_JPEG(ov2640_resolution_t res)
{
    OV2640_Init();
    OV2640_Write_Array(OV2640_JPEG_INIT);
    OV2640_Set_Resolution(res);
    OV2640_Set_JPEG_Quality(0x10);
    return 0;
}

uint16_t OV2640_ReadID(void)
{
    uint16_t id = 0;
    OV2640_WR_Reg(OV2640_DSP_RA_DLMT, OV2640_BANK_SENSOR);
    id = (OV2640_RD_Reg(OV2640_SENSOR_PIDH) << 8);
    id |= OV2640_RD_Reg(OV2640_SENSOR_PIDL);
    return id;
}