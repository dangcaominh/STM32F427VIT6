uint8_t OV2640_WR_Reg(uint8_t reg, uint8_t value)
{
    return (HAL_I2C_Mem_Write(&hi2c1, OV2640_DEVICE_ADDR, reg, 
                              I2C_MEMADD_SIZE_8BIT, &value, 1, 100) == HAL_OK) ? 0 : 1;
}

uint8_t OV2640_RD_Reg(uint8_t reg)
{
    uint8_t val = 0;
    HAL_I2C_Mem_Read(&hi2c1, OV2640_DEVICE_ADDR, reg, 
                     I2C_MEMADD_SIZE_8BIT, &val, 1, 100);
    return val;
}

